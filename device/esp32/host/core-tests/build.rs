//! Compiles the portable C protocol core (`components/im_core/*.c`) for the host with the
//! strictest warning level the toolchain offers, and generates the Rust error-code table from
//! `im_err.h` so the two can never drift apart.
//!
//! With `--features fuzz` the C is additionally instrumented for libFuzzer (SanitizerCoverage)
//! and AddressSanitizer: on MSVC `/fsanitize=address /fsanitize-coverage=inline-8bit-counters
//! /fsanitize-coverage=edge /fsanitize-coverage=trace-cmp`, elsewhere the clang equivalents.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let core = manifest.join("../../components/im_core");
    let include = core.join("include");

    let mut files: Vec<PathBuf> = fs::read_dir(&core)
        .expect("components/im_core must exist")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "c"))
        .collect();
    files.sort();
    assert!(!files.is_empty(), "no C sources in {}", core.display());

    let mut build = cc::Build::new();
    build
        .include(&include)
        .include(&core)
        .files(&files)
        .warnings(true)
        .warnings_into_errors(true);
    let compiler = build.get_compiler();
    let fuzz = env::var_os("CARGO_FEATURE_FUZZ").is_some();
    if compiler.is_like_msvc() {
        // /W4 /WX is the MSVC equivalent of -Wall -Wextra -Werror. No suppressions are needed.
        build.flag("/std:c11").flag("/sdl");
        if fuzz {
            build
                .flag("/fsanitize-coverage=inline-8bit-counters")
                .flag("/fsanitize-coverage=edge")
                .flag("/fsanitize-coverage=trace-cmp");
            // MSVC's SanitizerCoverage glue (_Sancov8bitUsed, section bounds -> libFuzzer's
            // __sanitizer_cov_8bit_counters_init) lives in libsancov.lib.
            println!("cargo:rustc-link-lib=libsancov");
            // rustc's ASan runtime and MSVC's cannot coexist in one process ("Interception
            // failure"). Run `cargo fuzz run -s none ...` so the C core gets MSVC's ASan and its
            // runtime is the only one; with Rust ASan enabled the C keeps coverage only.
            let rustflags = env::var("CARGO_ENCODED_RUSTFLAGS").unwrap_or_default();
            if !rustflags.contains("sanitizer=address") {
                build.flag("/fsanitize=address");
                println!("cargo:rustc-link-lib=clang_rt.asan_dynamic-x86_64");
                println!("cargo:rustc-link-lib=clang_rt.asan_dynamic_runtime_thunk-x86_64");
            }
            println!("cargo:rerun-if-env-changed=CARGO_ENCODED_RUSTFLAGS");
        }
    } else {
        build
            .flag("-std=c99")
            .flag("-Wextra")
            .flag("-Wshadow")
            .flag("-Wconversion")
            .flag("-Wno-sign-conversion");
        if fuzz {
            build.flag("-fsanitize=address,fuzzer-no-link").flag("-g");
        }
    }
    build.compile("im_core");

    // A directory entry makes cargo rescan it, so new C files trigger a rebuild too.
    println!("cargo:rerun-if-changed={}", core.display());
    for f in &files {
        println!("cargo:rerun-if-changed={}", f.display());
    }
    for e in fs::read_dir(&include).expect("include dir").flatten() {
        println!("cargo:rerun-if-changed={}", e.path().display());
    }
    for e in fs::read_dir(&core).expect("core dir").flatten() {
        if e.path().extension().is_some_and(|x| x == "h") {
            println!("cargo:rerun-if-changed={}", e.path().display());
        }
    }

    // Error code table: parse the X-macro list in im_err.h (order defines the enum values).
    let header = fs::read_to_string(include.join("im_err.h")).expect("im_err.h");
    let mut out = String::from("// @generated by build.rs from components/im_core/include/im_err.h\n");
    let mut names = Vec::new();
    for line in header.lines() {
        let l = line.trim_start();
        if let Some(rest) = l.strip_prefix("X(") {
            let mut parts = rest.splitn(2, ',');
            let ident = parts.next().unwrap().trim();
            let text = parts.next().unwrap();
            let text = text.split('"').nth(1).unwrap();
            names.push((ident.to_string(), text.to_string()));
        }
    }
    assert!(names.len() > 80, "error list not parsed");
    for (i, (ident, _)) in names.iter().enumerate() {
        out.push_str(&format!("pub const {ident}: i32 = {i};\n"));
    }
    out.push_str("pub const ERR_NAMES: &[&str] = &[\n");
    for (_, text) in &names {
        out.push_str(&format!("    \"{text}\",\n"));
    }
    out.push_str("];\n");
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("err_codes.rs");
    fs::write(dest, out).expect("write err_codes.rs");
}
